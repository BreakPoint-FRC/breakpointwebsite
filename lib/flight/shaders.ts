export const QH = [
  'vec3 qrot(vec4 q, vec3 v){ return v + 2.0 * cross(q.xyz, cross(q.xyz, v) + q.w * v); }',
  'vec4 qmul(vec4 a, vec4 b){ return vec4(a.w * b.xyz + b.w * a.xyz + cross(a.xyz, b.xyz), a.w * b.w - dot(a.xyz, b.xyz)); }',
  'vec4 qaxis(vec3 ax, float an){ float s = sin(an * 0.5); return vec4(ax * s, cos(an * 0.5)); }'
].join('\n');
export const HGT = [
  '  float area2 = abs((V1.x - V0.x) * (V2.y - V0.y) - (V1.y - V0.y) * (V2.x - V0.x));',
  '  vH = vec3(area2 / max(length(V2 - V1), 1e-4), area2 / max(length(V0 - V2), 1e-4), area2 / max(length(V1 - V0), 1e-4));'
].join('\n');

